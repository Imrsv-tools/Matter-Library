#!/usr/bin/env python3
"""Import Poly Haven HDRIs into the library, credited in full (Phase14).

Poly Haven (https://polyhaven.com) publishes every asset under CC0 1.0. It is the ONLY HDRI
source this tool fetches from: the hosts are fixed below. Its API is free for any use and asks
for two things (https://polyhaven.com/our-api): a unique User-Agent, sent on every request
here, and attribution, which the record, CREDITS.md and LICENSE-CONTENT.md carry.

    import_polyhaven_hdri.py list --category "pure skies"     # Poly Haven ids -> library names
    import_polyhaven_hdri.py import <polyhaven-id> [--name <Name>_<Variant>]
    import_polyhaven_hdri.py import --category "pure skies"   # every HDRI in the category
    import_polyhaven_hdri.py credits                          # regenerate CREDITS.md §HDRI sources

`import` does, per HDRI (Identity.md §HDRI names):
  1. names it: a `<name>_puresky` id becomes `<Name>_PureSky` (PascalCase tokens); any other id
     needs `--name`. Version v01.
  2. downloads the 4k Radiance `.hdr`, checks its size and Poly Haven's MD5, then runs the
     library's HDRI check (`validate_manifest.check_hdri`: name, RGBE, 4096 x 2048), and only
     then writes MatterLibrary/hdris/<id>_v01.hdr. The bytes are Poly Haven's, unchanged.
  3. records it at library/provenance/sources/hdris/<id>.yaml: the `provenance:` block a release
     lock will carry (source, CC0-1.0, the asset page, the file URL, sha256), and everything Poly
     Haven credits and tags: its name, description, the line naming what it was edited from, the
     contributors and their roles, its sponsors (resolved to name and link), its tags,
     categories and attributes, and when and where it was captured (RD-P14-2, "over crediting").
  4. regenerates CREDITS.md §HDRI sources from every record.

It never overwrites: an HDRI already in the library is skipped. Standard library + PyYAML.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import re
import shutil
import sys
import tempfile
import urllib.parse
import urllib.request
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT / "tools" / "validators"))
import validate_manifest as vm  # noqa: E402  (check_hdri: the one HDRI check)

SITE = "https://polyhaven.com"
API = "https://api.polyhaven.com"
DL = "https://dl.polyhaven.org/"
ALLOWED = (API + "/", DL)                     # the only hosts fetched from (CC0 1.0)
USER_AGENT = "MatterLibrary-tools/1.0 (+https://github.com/Imrsv-tools/Matter-Library)"
RES = "4k"                                    # 4096 x 2048: RD-SKY-3
HDRIS = ROOT / "MatterLibrary" / "hdris"
RECORDS = ROOT / "library" / "provenance" / "sources" / "hdris"
CREDITS = ROOT / "CREDITS.md"
CREDITS_START = "<!-- hdri-credits:start (generated by tools/converters/import_polyhaven_hdri.py credits) -->"
CREDITS_END = "<!-- hdri-credits:end -->"


def _get(url: str) -> bytes:
    if not url.startswith(ALLOWED):
        raise SystemExit(f"refusing to fetch outside Poly Haven: {url}")
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=300) as resp:
        return resp.read()


def _json(path: str):
    return json.loads(_get(f"{API}/{path}"))


def category_ids(category: str) -> list[str]:
    q = urllib.parse.urlencode({"type": "hdris", "categories": category})
    return sorted(_json(f"assets?{q}"))


def library_id(polyhaven_id: str, name: str | None = None) -> str:
    """The library id for a Poly Haven id: `<x>_puresky` -> `<X>_PureSky`; otherwise --name."""
    if name:
        hid = name
    elif polyhaven_id.endswith("_puresky"):
        base = polyhaven_id[: -len("_puresky")]
        hid = "".join(t[:1].upper() + t[1:] for t in base.split("_")) + "_PureSky"
    else:
        raise SystemExit(f"{polyhaven_id}: not a pure sky, so give its library name with --name <Name>_<Variant>")
    if not vm.HDRI_STEM_RE.match(f"{hid}_v01"):
        raise SystemExit(f"{hid!r} is not <Name>_<Variant> (PascalCase tokens)")
    return hid


def _sponsors(ids) -> list[dict]:
    out = []
    for sid in ids or []:
        s = _json(f"sponsor/{urllib.parse.quote(str(sid))}")
        out.append({"id": str(sid), "name": s.get("name", ""), **({"url": s["url"]} if s.get("url") else {})})
    return out


def _date(epoch) -> str | None:
    return dt.datetime.fromtimestamp(epoch, dt.timezone.utc).date().isoformat() if epoch else None


def import_one(polyhaven_id: str, name: str | None = None) -> str:
    hid = library_id(polyhaven_id, name)
    version = "v01"
    dst = HDRIS / f"{hid}_{version}.hdr"
    rec = RECORDS / f"{hid}.yaml"
    if dst.exists() or rec.exists():
        print(f"  skip   {hid}: already in the library")
        return "skipped"

    info = _json(f"info/{polyhaven_id}")
    f = _json(f"files/{polyhaven_id}")["hdri"][RES]["hdr"]
    data = _get(f["url"])
    if len(data) != f["size"]:
        raise SystemExit(f"{polyhaven_id}: {len(data)} bytes, Poly Haven lists {f['size']}")
    if f.get("md5") and hashlib.md5(data).hexdigest() != f["md5"]:  # noqa: S324  (Poly Haven's own checksum)
        raise SystemExit(f"{polyhaven_id}: MD5 does not match Poly Haven's")
    with tempfile.TemporaryDirectory() as tmp:
        probe = Path(tmp) / dst.name
        probe.write_bytes(data)
        errs = vm.check_hdri(probe)
        if errs:
            raise SystemExit(f"{polyhaven_id}: refused by the HDRI check: {'; '.join(errs)}")
        HDRIS.mkdir(parents=True, exist_ok=True)
        shutil.move(probe, dst)

    record = {
        "id": hid,
        "version": version,
        "status": "candidate",                       # passed the HDRI check (Manifest lifecycle)
        "file": dst.relative_to(ROOT).as_posix(),
        "provenance": {
            "source": "Poly Haven",
            "license": "CC0-1.0",
            "evidence": {
                "url": f"{SITE}/a/{polyhaven_id}",
                "file_url": f["url"],
                "sha256_scope": "file",
                "sha256": hashlib.sha256(data).hexdigest(),
                "md5": f.get("md5", ""),
            },
        },
        "credit": {
            "source": "Poly Haven",
            "source_url": SITE,
            "asset_id": polyhaven_id,
            "asset_url": f"{SITE}/a/{polyhaven_id}",
            "name": info.get("name", ""),
            "authors": [{"name": a, "role": r} for a, r in (info.get("authors") or {}).items()],
            "sponsors": _sponsors(info.get("sponsors")),
            "info": info.get("info", ""),
        },
        "description": info.get("description", ""),
        "tagging": {
            "tags": info.get("tags") or [],
            "categories": info.get("categories") or [],
            "attributes": info.get("attributes") or {},
        },
        "captured": {k: v for k, v in {
            "date_taken": _date(info.get("date_taken")),
            "whitebalance": info.get("whitebalance"),
            "evs_cap": info.get("evs_cap"),
            "coords": info.get("coords"),
        }.items() if v is not None},
        "poly_haven": {"date_published": _date(info.get("date_published")),
                       "files_hash": info.get("files_hash", "")},
        "retrieved": dt.date.today().isoformat(),
    }
    RECORDS.mkdir(parents=True, exist_ok=True)
    rec.write_text(
        "# One HDRI's record (Phase14): its provenance block, which a release lock carries, and\n"
        "# everything Poly Haven credits and tags. Written by tools/converters/import_polyhaven_hdri.py.\n"
        + yaml.safe_dump(record, sort_keys=False, allow_unicode=True, width=200), encoding="utf-8")
    print(f"  import {hid}  <- {polyhaven_id}  ({len(data) / 1e6:.1f} MB)")
    return "imported"


def _md_link(text: str, url: str) -> str:
    return f"[{text}]({url})" if url else text


def write_credits() -> int:
    """CREDITS.md §HDRI sources, regenerated from every record (sorted, so it is deterministic)."""
    rows, people = [], {}
    for p in sorted(RECORDS.glob("*.yaml")):
        r = yaml.safe_load(p.read_text(encoding="utf-8"))
        c = r["credit"]
        authors = ", ".join(f"{a['name']} ({a['role']})" for a in c["authors"])
        sponsors = ", ".join(_md_link(s["name"], s.get("url", "")) for s in c.get("sponsors", []))
        for a in c["authors"]:
            people.setdefault(a["name"], set()).add(a["role"])
        rows.append(f"| `{r['id']}` | [{c['name']}]({c['asset_url']}) | {authors} | {sponsors or '—'} | CC0-1.0 |")
    contributors = "; ".join(f"**{n}** ({', '.join(sorted(roles))})" for n, roles in sorted(people.items()))
    section = "\n".join([
        CREDITS_START,
        "## HDRI sources",
        "",
        "Every HDRI in `MatterLibrary/hdris/` comes from **[Poly Haven](https://polyhaven.com)**, which publishes it "
        "under CC0-1.0. Each one's full record (its Poly Haven page, contributors and their roles, sponsors, tags "
        "and where it was captured) is in `library/provenance/sources/hdris/`.",
        "",
        f"**Poly Haven contributors to these HDRIs:** {contributors}." if people else "",
        "",
        "| HDRI | On Poly Haven | Contributors (role) | Sponsored by | Licence |",
        "|---|---|---|---|---|",
        *rows,
        CREDITS_END,
    ])
    text = CREDITS.read_text(encoding="utf-8")
    if CREDITS_START in text:
        before, rest = text.split(CREDITS_START, 1)
        after = rest.split(CREDITS_END, 1)[1]
        text = before + section + after
    else:
        anchor = "\n## Built on"
        if text.count(anchor) != 1:
            raise SystemExit("CREDITS.md: '## Built on' anchor not found; add the section by hand")
        text = text.replace(anchor, "\n" + section + "\n" + anchor, 1)
    CREDITS.write_text(text, encoding="utf-8")
    print(f"  CREDITS.md §HDRI sources: {len(rows)} HDRI(s), {len(people)} contributor(s)")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Import Poly Haven HDRIs into the Matter Library, credited.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    ls = sub.add_parser("list")
    ls.add_argument("--category", required=True)
    im = sub.add_parser("import")
    im.add_argument("polyhaven_id", nargs="?")
    im.add_argument("--name", help="the library id <Name>_<Variant>, for an id that is not a pure sky")
    im.add_argument("--category", help="import every HDRI in this Poly Haven category")
    sub.add_parser("credits")
    args = ap.parse_args(argv)

    if args.cmd == "list":
        for pid in category_ids(args.category):
            print(f"{pid:<40} {library_id(pid)}_v01.hdr")
        return 0
    if args.cmd == "credits":
        return write_credits()
    if bool(args.polyhaven_id) == bool(args.category):
        raise SystemExit("import takes one Poly Haven id or --category, not both")
    ids = [args.polyhaven_id] if args.polyhaven_id else category_ids(args.category)
    done = [import_one(pid, args.name if args.polyhaven_id else None) for pid in ids]
    print(f"  {done.count('imported')} imported, {done.count('skipped')} already in the library")
    return write_credits()


if __name__ == "__main__":
    raise SystemExit(main())
